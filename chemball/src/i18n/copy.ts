export type Copy = typeof en;

export function text(language: Language): Copy {
  return language === "fa" ? fa : en;
}

export function materialName(language: Language, id: string): string {
  return materialNames[language][id] ?? materialNames.en[id] ?? id;
}

export function summaryLine(language: Language, reactions: number, matches: number, chain: number): string {
  if (language === "fa") return `${reactions} واکنش · ${matches} جور · زنجیره ${chain}`;
  return `${reactions} reactions · ${matches} matches · chain ${chain}`;
}

export function hiddenLine(language: Language, count: number): string {
  if (language === "fa") return `${count} واکنش هنوز پنهان است`;
  return `${count} reactions still hidden`;
}
