const BY_ID = new Map(REACTIONS.map((reaction) => [reaction.id, reaction]));

export function getReaction(id: string): ReactionDef {
  const reaction = BY_ID.get(id);
  if (!reaction) throw new Error(`Unknown reaction ${id}`);
  return reaction;
}

export function sortedReactions(): ReactionDef[] {
  return [...REACTIONS].sort(
    (a, b) => b.priority - a.priority || b.minRequired - a.minRequired || b.scoreValue - a.scoreValue,
  );
}
