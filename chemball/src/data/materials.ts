const BY_ID = new Map(MATERIALS.map((material) => [material.id, material]));

export function getMaterial(id: string): MaterialDef {
  const material = BY_ID.get(id);
  if (!material) throw new Error(`Unknown material ${id}`);
  return material;
}

export function isRisingMaterial(id: string | undefined): boolean {
  if (!id) return false;
  return getMaterial(id).movement === "rising";
}
